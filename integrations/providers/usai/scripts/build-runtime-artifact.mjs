// Dependency-free build-time bundling of a CLOSED source list. No runtime eval,
// dynamic imports, resolver, network, or provider-controlled source is involved.
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath, pathToFileURL } from "node:url"
import path from "node:path"

const root = new URL("../../../../", import.meta.url)
const guest = "integrations/isolation/acq-kits/opencode/files/home/opencode-config/"
export const artifactPath = new URL(guest + "runtime-model-preparation.mjs", root)
const sources = [
  "integrations/providers/usai/scripts/model-catalog-core.mjs",
  "integrations/providers/usai/scripts/runtime-model-bounds.mjs",
  "integrations/providers/usai/scripts/runtime-model-discovery.mjs",
  guest + "render-provider-config.mjs",
  guest + "runtime-preparation-source.mjs",
]

export async function buildRuntimeArtifact() {
  const imports = []
  const modules = []
  for (const [index, source] of sources.entries()) {
    let text = await readFile(new URL(source, root), "utf8")
    if (source.endsWith("render-provider-config.mjs")) {
      const marker = "// Compare URL against URL so the check is portable:"
      if (!text.includes(marker)) throw new Error("renderer entrypoint boundary changed")
      text = text.slice(0, text.indexOf(marker))
    }
    const exports = [...text.matchAll(/^export (?:async )?(?:function|const) (\w+)/gm)].map((match) => match[1])
    text = text.replace(/^#!.*\n/, "").replace(/^import (.+) from "([^"]+)"\n/gm, (_, binding, specifier) => {
      let target
      if (specifier.startsWith("node:")) {
        target = `builtin${imports.length}`
        imports.push(`import * as ${target} from ${JSON.stringify(specifier)}`)
        if (!binding.startsWith("{")) return `const ${binding} = ${target}.default\n`
      } else {
        const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(source), specifier))
        const dependency = sources.indexOf(resolved)
        if (dependency < 0 || dependency >= index) throw new Error("unreviewed runtime dependency")
        target = `module${dependency}`
      }
      return `const ${binding} = ${target}\n`
    }).replace(/^export /gm, "")
    if (/^import /m.test(text)) throw new Error("unsupported runtime import syntax")
    modules.push(`// Source: ${source}\nconst module${index} = await (async () => {\n${text}\nreturn { ${exports.join(", ")} }\n})()\n`)
  }
  return "// GENERATED by build-runtime-artifact.mjs; edit the named sources, not this file.\n" +
    imports.join("\n") + "\n\n" + modules.join("\n") +
    "\nexport const { prepareRuntimeModels, runDiscoveryChild, runtimePreparationMain } = module4\n"
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = process.argv.slice(2)
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) throw new Error("usage: build-runtime-artifact.mjs [--check]")
  const expected = await buildRuntimeArtifact()
  if (args[0] === "--check") {
    if (await readFile(artifactPath, "utf8") !== expected) throw new Error("standalone runtime artifact differs from canonical sources")
  } else await writeFile(fileURLToPath(artifactPath), expected)
}
